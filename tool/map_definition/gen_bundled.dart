// Writes lib/core/map_definition_bundled.g.dart from assets/map/map-definition.json (= the M1 fixture,
// meshsonar-infra docs/planning/map-definition-fixture.json). The app reads the bundled definition synchronously from this
// constant (the theme and the first frame need colours before any asset or network read finishes); the asset stays the
// file copy. test/core/map_definition_render_test.dart fails when the two differ.
//
// Run from the repo root after copying a new fixture:  dart run tool/map_definition/gen_bundled.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final src = File('assets/map/map-definition.json').readAsStringSync();
  jsonDecode(src); // must be JSON
  if (src.contains("'''")) throw StateError('the definition contains three single quotes; pick another delimiter');
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/map_definition/gen_bundled.dart from assets/map/map-definition.json. Do not edit.')
    ..writeln('// The bundled Map Definition (the M1 fixture): the app renders from it until the server copy arrives.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln("const String kBundledMapDefinitionJson = r'''")
    ..write(src.endsWith('\n') ? src : '$src\n')
    ..writeln("''';");
  File('lib/core/map_definition_bundled.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote lib/core/map_definition_bundled.g.dart');
}
